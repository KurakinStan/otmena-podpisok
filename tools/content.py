# ---------- Общие способы: магазины приложений ----------
# {name} подставляется названием сервиса.

def appstore(name):
    return ('Если платили через App Store (iPhone, iPad)', [
        'Откройте «Настройки» и нажмите на своё имя вверху',
        'Выберите «Подписки»',
        f'Найдите {name} в списке и нажмите «Отменить подписку». Кнопка может быть в самом низу экрана',
        'Без iPhone то же самое можно сделать в браузере: account.apple.com → «Подписки»',
    ])


def googleplay(name):
    return ('Если платили через Google Play (Android)', [
        'Откройте Google Play и нажмите на значок профиля справа вверху',
        'Выберите «Платежи и подписки» → «Подписки»',
        f'Нажмите на {name} → «Отменить подписку» и подтвердите',
    ])


def rustore(name):
    return ('Если платили через RuStore', [
        'Откройте RuStore и перейдите на вкладку «Моё»',
        'Откройте раздел «Подписки»',
        f'Выберите {name} и нажмите «Отменить подписку»',
    ])


def stores(name):
    """Все три магазина одним списком."""
    return [appstore(name), googleplay(name), rustore(name)]


