# Контент сайта: инструкции по отмене подписок.
#
# Это единственный файл, который нужно править, чтобы поменять текст на
# сайте. После правки запустите  python3 tools/build.py  — он пересоберёт
# все HTML-страницы.
#
# Поля сервиса:
#   slug     — адрес страницы (латиницей): /<slug>/
#   name     — название сервиса, как его ищут люди
#   cat      — раздел на главной (ключи из CATEGORIES)
#   search   — дополнительные слова для поиска на сайте
#   lead     — короткий ответ в начале страницы (1–3 предложения)
#   link     — (адрес, подпись кнопки): куда идти отменять
#   help     — официальная справка сервиса (или None)
#   methods  — способы отмены: [(заголовок, [шаги])]
#   notes    — важные особенности
#   after    — что будет после отмены (если None — общий текст)
#   refund   — как вернуть деньги (если None — общий текст)
#   faq      — дополнительные вопросы: [(вопрос, ответ)]
#   related  — slug'и похожих сервисов
#
# Источники: справки сервисов (ссылка help) и проверенные шаги из базы
# расширения «Трекер подписок» (services-db.js). Обновлено: октябрь 2026.

